import { test } from "node:test";
import assert from "node:assert/strict";
import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";
import { ensureNpm } from "../src/npm-cache.ts";
import { exists } from "../src/files.ts";

test("真实 npm 安装成功后复用；安装条件改变、强制重建和失败均不误用旧标记", async t => {
  const cwd = await fs.mkdtemp(path.join(os.tmpdir(), "cs-npm-cache-test-"));
  t.after(() => fs.rm(cwd, { recursive: true, force: true }));
  const manifest = { name: "cache-probe", version: "1.0.0", scripts: { install: "node install.cjs" } };
  await fs.writeFile(path.join(cwd, "package.json"), JSON.stringify(manifest), "utf8");
  await fs.writeFile(path.join(cwd, "package-lock.json"), JSON.stringify({ name: manifest.name, version: "1.0.0", lockfileVersion: 3, packages: { "": { name: manifest.name, version: "1.0.0", hasInstallScript: true } } }), "utf8");
  await fs.writeFile(path.join(cwd, "install.cjs"), "require('fs').appendFileSync('installed.txt','x')", "utf8");
  const args = ["--offline"], run = (fresh = false) => ensureNpm({ cwd, args, fresh });
  assert.deepEqual(await run(), { reused: false, code: 0 });
  assert.deepEqual(await run(), { reused: true, code: 0 });
  assert.equal(await fs.readFile(path.join(cwd, "installed.txt"), "utf8"), "x");
  await fs.writeFile(path.join(cwd, ".npmrc"), "legacy-peer-deps=true\n", "utf8");
  assert.deepEqual(await run(), { reused: false, code: 0 });
  assert.deepEqual(await run(), { reused: true, code: 0 });
  assert.deepEqual(await ensureNpm({ cwd, args: [...args, "--ignore-scripts"] }), { reused: false, code: 0 });
  await fs.writeFile(path.join(cwd, "install.cjs"), "process.exit(7)", "utf8");
  assert.equal((await run(true)).code, 7);
  assert.equal(await exists(path.join(cwd, "node_modules", ".cs-agent-npm.json")), false);
  await fs.writeFile(path.join(cwd, "install.cjs"), "require('fs').appendFileSync('installed.txt','x')", "utf8");
  assert.deepEqual(await run(), { reused: false, code: 0 });
  assert.deepEqual(await run(), { reused: true, code: 0 });
  await assert.rejects(ensureNpm({ cwd, args: ["--prefix=elsewhere"] }), /unsupported_npm_option/);
});
