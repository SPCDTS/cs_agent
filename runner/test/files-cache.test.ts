import { test } from "node:test";
import assert from "node:assert/strict";
import { promises as fs } from "node:fs";
import path from "node:path";
import os from "node:os";
import { NpmCache } from "../src/cache.ts";
import { snapshot, restore, sha256, removeInside, plainFile } from "../src/files.ts";
test("快照保留中文与二进制，忽略依赖/仓库缓存，按哈希恢复", async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "cs-agent-source-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const source = path.join(root, "source"), objects = path.join(root, "objects"), target = path.join(root, "target");
  await fs.mkdir(path.join(source, "node_modules"), { recursive: true });
  await fs.mkdir(path.join(source, ".git")); await fs.mkdir(path.join(source, ".wrangler"));
  await fs.writeFile(path.join(source, "中文.txt"), "你好\r\n内容", "utf8");
  await fs.writeFile(path.join(source, "binary.bin"), Buffer.from([0, 255, 1]));
  await fs.writeFile(path.join(source, "node_modules/large.dat"), "不是源文件");
  const manifest = await snapshot(source, objects); assert.equal(manifest.files.length, 2);
  await restore(target, manifest, objects);
  assert.equal(await fs.readFile(path.join(target, "中文.txt"), "utf8"), "你好\r\n内容");
  assert.deepEqual(await fs.readFile(path.join(target, "binary.bin")), Buffer.from([0, 255, 1]));
  await fs.writeFile(path.join(objects, manifest.files[0]!.sha256), "corrupt");
  await assert.rejects(restore(path.join(root, "corrupt"), manifest, objects), /blob_corrupt/);
  await assert.rejects(removeInside(root, root), /path_denied/);
});
test("npm 缓存工作区隔离、配额淘汰、拒绝 junction，校验失败不发布", async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "cs-agent-cache-")); t.after(() => fs.rm(root, { recursive: true, force: true }));
  const cache = new NpmCache(path.join(root, "cache"), 30, 35), source = path.join(root, "source");
  await fs.mkdir(path.join(source, "_cacache"), { recursive: true });
  await fs.writeFile(path.join(source, "_cacache/content"), "a".repeat(20));
  const first = cache.key("owner", "v24"), second = cache.key("sub", "v24");
  assert.notEqual(first, second);
  await cache.promote(first, source, async () => undefined);
  assert.equal(await cache.seed(first, path.join(root, "lease-one")), true);
  await cache.promote(second, source, async () => undefined);
  assert.equal(await cache.seed(first, path.join(root, "lease-two")), false);
  assert.equal(await cache.seed(second, path.join(root, "lease-three")), true);
  await assert.rejects(cache.promote(first, source, async () => { throw new Error("integrity"); }), /integrity/);
  assert.equal(await cache.seed(first, path.join(root, "lease-four")), false);
  await fs.symlink(path.join(root, "lease-three"), path.join(source, "_cacache/link"), "junction");
  await assert.rejects(cache.promote(first, source, async () => undefined), /cache_link_denied/);
  await assert.rejects(plainFile(source, "_cacache/link/_cacache/content"), /path_denied/);
  assert.equal(sha256("a").length, 64);
});
