import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';
import { request } from 'node:http';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { CallToolResultSchema } from '@modelcontextprotocol/sdk/types.js';
import { createDesktopServer } from '../src/desktop-server.ts';
import type { DesktopConfig } from '../src/desktop-config.ts';

test('独立桌面 HTTP MCP：真实 stdio、schema/图片透传、身份校验、引用隔离和未知结果不重放', { timeout: 30_000 }, async t => {
  const dir = await mkdtemp(join(tmpdir(), 'desktop-http-'));
  const marker = join(dir, 'calls.txt');
  const fixture = fileURLToPath(new URL('./fixtures/desktop-fixture.ts', import.meta.url));
  const config: DesktopConfig = { host: '127.0.0.1', port: 7792, token: 'a'.repeat(64), desktopSid: 'S-1-5-21', command: process.execPath, args: [fixture, marker], cwd: dirname(fixture), scopeArgument: '--session' };
  let stamp = 'desktop-session-1', locked = false, guards = 0;
  const service = createDesktopServer(config, async () => { guards++; if (locked) throw new Error('desktop_unavailable'); return stamp; }, { callTimeoutMs: 2500 });
  await new Promise<void>(resolve => service.server.listen(0, config.host, resolve));
  const address = service.server.address(); assert.ok(address && typeof address !== 'string');
  const url = new URL(`http://127.0.0.1:${address.port}/mcp`);
  const client = new Client({ name: 'desktop-test', version: '1' });
  t.after(async () => { await client.close(); await service.close(); await rm(dir, { recursive: true, force: true }); });
  const headers = { Authorization: 'Bearer ' + config.token, 'Content-Type': 'application/json', Accept: 'application/json, text/event-stream' };
  await client.connect(new StreamableHTTPClientTransport(url, { requestInit: { headers } }));
  const catalog = await client.listTools();
  assert.equal(catalog.tools[0]?.inputSchema.additionalProperties, false);
  assert.equal(catalog.tools[0]?.name, 'desktop_fixture');
  assert.match(client.getInstructions()!, /共享/);
  const call = async (mode = '', scope = 'a'.repeat(64)) => CallToolResultSchema.parse(await client.callTool({ name: 'desktop_fixture', arguments: { mode }, _meta: { 'cs-agent/caller': { scope } } }));
  const first = await call();
  assert.deepEqual(first.content, [{ type: 'text', text: '原生文本' }, { type: 'image', mimeType: 'image/png', data: 'aGVsbG8=' }]);
  assert.equal(first.structuredContent?.calls, 1);
  const second = await call();
  assert.equal(second.structuredContent?.calls, 2);
  assert.equal(second.structuredContent?.namespace, first.structuredContent?.namespace);
  const foreign = await call('', 'b'.repeat(64));
  assert.equal(foreign.structuredContent?.calls, 1);
  assert.notEqual(foreign.structuredContent?.namespace, first.structuredContent?.namespace);
  const before = guards;
  assert.equal((await fetch(url, { method: 'POST' })).status, 401);
  assert.equal((await fetch(url, { method: 'POST', headers: { ...headers, Origin: 'https://attacker.example' }, body: '{}' })).status, 403);
  const badHost = await new Promise<number>(resolve => { const req = request(url, { method: 'POST', headers: { ...headers, Host: 'attacker.example' } }, res => { res.resume(); resolve(res.statusCode!); }); req.end('{}'); });
  assert.equal(badHost, 403);
  assert.equal((await fetch(url, { headers })).status, 405);
  assert.equal((await fetch(url, { method: 'POST', headers, body: '{' })).status, 400);
  assert.equal((await fetch(url, { method: 'POST', headers, body: 'x'.repeat(512 * 1024 + 1) })).status, 413);
  assert.equal((await call('', '')).isError, true);
  assert.equal(guards, before);
  locked = true;
  assert.deepEqual((await call()).content, [{ type: 'text', text: 'desktop_unavailable' }]);
  locked = false;
  assert.equal((await call()).structuredContent?.calls, 3);
  stamp = 'desktop-session-2';
  const changed = await call();
  assert.notEqual(changed.structuredContent?.namespace, first.structuredContent?.namespace);
  assert.equal(changed.structuredContent?.calls, 1);
  const error = await call('reject');
  assert.equal(error.isError, true); assert.deepEqual(error.structuredContent, { disposition: { retry: 'unsafe' } });
  assert.deepEqual((await call('crash')).content, [{ type: 'text', text: 'desktop_mcp_outcome_unknown' }]);
  assert.equal(await readFile(marker, 'utf8'), 'invoked\n');
  await call();
  const slow = call('slow');
  await new Promise(resolve => setTimeout(resolve, 100));
  await assert.rejects(fetch(url, { method: 'POST', headers, signal: AbortSignal.timeout(150), body: JSON.stringify({ jsonrpc: '2.0', id: 99, method: 'tools/call', params: { name: 'desktop_fixture', arguments: { mode: 'crash' }, _meta: { 'cs-agent/caller': { scope: 'a'.repeat(64) } } } }) }));
  assert.deepEqual((await slow).content, [{ type: 'text', text: 'desktop_mcp_outcome_unknown' }]);
  await call();
  assert.equal(await readFile(marker, 'utf8'), 'invoked\n');
});

test('独立桌面身份检查器可单独编译，拒绝非目标用户', { skip: process.platform !== 'win32' || process.env.CS_AGENT_TEST_HYPERV_NATIVE !== '1' }, async t => {
  const dir = await mkdtemp(join(tmpdir(), 'desktop-context-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const exe = join(dir, 'DesktopContext.exe');
  const compiler = join(process.env.SystemRoot ?? 'C:/Windows', 'Microsoft.NET/Framework64/v4.0.30319/csc.exe');
  const execute = promisify(execFile);
  await execute(compiler, ['/nologo', '/target:winexe', '/out:' + exe, '/r:System.Web.Extensions.dll', '/r:System.Drawing.dll', '/r:System.Windows.Forms.dll', fileURLToPath(new URL('../native/desktop/Context.cs', import.meta.url))], { windowsHide: true });
  const { stdout } = await execute(exe, ['S-1-5-0'], { windowsHide: true });
  assert.equal(JSON.parse(stdout), null);
});
