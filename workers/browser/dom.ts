export type Child = Node | string | number | null | undefined;
export type Props = { text?: unknown; className?: string; onclick?: (event: MouseEvent) => unknown; onchange?: (event: Event) => unknown; ontoggle?: (event: Event) => unknown; [attribute: string]: unknown };
export function el<K extends keyof HTMLElementTagNameMap>(tag: K, props: Props = {}, children: readonly Child[] = []): HTMLElementTagNameMap[K] {
 const node=document.createElement(tag);
 const {onclick,onchange,ontoggle,...attributes}=props;
 if(onclick)node.addEventListener("click",event => { if (event instanceof MouseEvent) onclick(event); });
 if(onchange)node.addEventListener("change",onchange);
 if(ontoggle)node.addEventListener("toggle",ontoggle);
 for(const [key,value]of Object.entries(attributes)){
  if(value===undefined||value===null||value===false)continue;
  if(key==="text")node.textContent=String(value);else if(key==="className")node.className=String(value);else node.setAttribute(key,String(value));
 }
 for(const child of children)if(child!==null&&child!==undefined)node.append(typeof child==="number"?String(child):child);
 return node;
}
